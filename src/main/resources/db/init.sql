-- PostgreSQL schema and starter content for the Bhargava Institute API.
-- Run against an empty database. Seed rows are intended to be inserted once.

CREATE TABLE IF NOT EXISTS banner (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    text VARCHAR(255) NOT NULL,
    link_to VARCHAR(255) NOT NULL,
    cta VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL,
    active BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    icon VARCHAR(255) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    level VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS lesson (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course (id),
    title VARCHAR(255) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    position INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS subject (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    icon VARCHAR(255) NOT NULL,
    description VARCHAR(500) NOT NULL,
    display_order INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS study_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    icon VARCHAR(255) NOT NULL,
    file_url VARCHAR(255),
    display_order INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS quiz_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text VARCHAR(500) NOT NULL,
    correct_answer VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS quiz_option (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES quiz_question (id),
    text VARCHAR(255) NOT NULL,
    position INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS contact_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

